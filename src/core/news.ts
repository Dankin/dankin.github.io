/** 跑马灯至少要有的行数 */
const MIN_LINES = 8;
/** 最多同时展示的已解锁头条数 */
const MAX_HEADLINES = 6;

/** 小型确定性随机数(mulberry32):同一个种子永远给出同一串数 */
function seededRandom(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Fisher-Yates 洗牌,返回新数组 */
function shuffled<T>(src: readonly T[], rand: () => number): T[] {
  const a = src.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/**
 * 跑马灯内容:已解锁头条(最近 6 条,最新的排最前)与冷笑话交错。
 * 冷笑话用 delivered 做种子洗牌后不放回地抽取,所以同一数量永远得到同一版,且整条跑马灯里不会出现重复行;
 * 总行数至少 8 条。
 */
export function tickerLines(delivered: number): string[] {
  const d = Number.isFinite(delivered) ? Math.max(0, delivered) : 0;
  const idx = newsIndex(d);
  const heads = NEWS.slice(Math.max(0, idx - (MAX_HEADLINES - 1)), idx + 1)
    .map((n) => n.text)
    .reverse();
  const rand = seededRandom((Math.floor(d) % 4294967296) ^ 0x9e3779b9);
  const pool = shuffled(Array.from(new Set(FILLER)), rand);
  const want = Math.max(MIN_LINES - heads.length, heads.length + 1);
  const fillers = pool.slice(0, Math.min(want, pool.length));
  const base = Math.floor(fillers.length / heads.length);
  const extra = fillers.length % heads.length;
  const out: string[] = [];
  let f = 0;
  heads.forEach((h, i) => {
    out.push(h);
    const n = base + (i < extra ? 1 : 0);
    for (let k = 0; k < n; k++) out.push(fillers[f++]);
  });
  return out;
}

export function newsIndex(delivered: number): number {
  let i = 0;
  for (let k = 0; k < NEWS.length; k++) if (delivered >= NEWS[k].at) i = k;
  return i;
}
