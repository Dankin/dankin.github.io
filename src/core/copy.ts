export const awayLine = (minutes: number): string =>
  minutes < 2 ? '你刚走开一会儿,苹果在继续送。'
  : minutes < 60 ? `你走开了 ${Math.round(minutes)} 分钟,车队没停。`
  : minutes < 24 * 60 ? `明信片:你走了 ${(minutes / 60).toFixed(1)} 小时。树说想你了,苹果一直在路上。`
  : minutes < 3 * 24 * 60 ? `明信片:一整天过去了。车队问你去哪了,老徐说你大概去过日子了。`
  : '明信片:三天了。树都开始自己摇自己了。欢迎回来。';

