// 新闻滚动条文案库(纯数据)。
// 用途:顶部/角落"苹果日报"滚动条,8 秒换一条。程序按 era(时代)与 when(条件标签)筛选,再按 weight 加权随机。
// 约束:每条 ≤26 字;不点真实品牌、公司;"与苹果公司无关"自嘲全局 ≤6 条(见 DISCLAIMER_NEWS_IDS)。
// 规则:id 一经使用不要改、不要重排(存档里可能记录"最近看过"的 id);新增请追加到各组末尾。
//
// 字段:
//   era    0..5 = 一棵树/篮子 … 苹果之门/传送门;缺省 = 任何时代都可出现。
//   when   条件标签,ALL 满足才可选(缺省 = 无条件)。标签含义见 NEWS_TAGS。
//   weight 抽取权重,缺省 1。条件条目建议 2–3(条件命中时优先于通用条)。

export type NewsEra = 0 | 1 | 2 | 3 | 4 | 5;

export interface NewsItem {
  id: string;
  text: string;
  era?: 0 | 1 | 2 | 3 | 4 | 5;
  when?: string[];
  weight?: number;
}

/** 条件标签及其含义(供 systems 实现判定) */
export const NEWS_TAGS = {
  night: '夜晚(昼夜时钟为夜)',
  day: '白天',
  rain: '下雨(天气系统)',
  snow: '下雪(天气系统,或 12 月)',
  'low-stock': '库存低(不够买最近的目标,或低于 10 秒收入)',
  'high-stock': '库存高(超过防囤线的 70%)',
  'new-tier': '刚升档后 60 秒内',
  idle: '30 秒以上无操作',
  xmas: '12/20 之后(或圣诞主题日)',
  gold: '金苹果刚出现过/图鉴已有金苹果',
  combo: '连摇 ≥20 击',
} as const;
export type NewsTag = keyof typeof NEWS_TAGS;

type Row = string | [text: string, when?: NewsTag[], weight?: number];

function build(prefix: string, era: NewsEra | undefined, rows: Row[]): NewsItem[] {
  return rows.map((r, i) => {
    const [text, when, weight] = typeof r === 'string' ? [r] : r;
    const item: NewsItem = { id: `${prefix}${String(i + 1).padStart(2, '0')}`, text };
    if (era !== undefined) item.era = era;
    if (when && when.length) item.when = when;
    if (weight !== undefined) item.weight = weight;
    return item;
  });
}

