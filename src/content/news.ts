export type NewsTag = keyof typeof NEWS_TAGS;

type Row = string | [text: string, when?: NewsTag[], weight?: number];

function build(prefix: string, era: NewsEra | undefined, rows: Row[]): NewsItem[] {
  return rows.map((r, i) => {
    const [text, when, weight] = typeof r === 'string' ? [r] : r;
    const item: NewsItem = { id: `${prefix}${String(i + 1).padStart(2, '0')}`, text };
    if (era !== undefined) item.era = era;
    if (when && when.length) item.when = when;
    if (weight !== undefined) item.weight = weight;
    return item;
  });
}

