// 角色口吻与台词库(纯数据)。
// 用途:旁白条头像+台词、事件弹出气泡、点击角色的反馈、彩蛋/时代切换时的角色发言。
// 约定:主角匿名,只被称作"你",不在此表中。每角色 ≥6 条台词,每条带触发场景(trigger,人话,供程序对接)。
// 约束:每条台词 ≤28 字(气泡内放得下)。id 稳定不改;新增追加在各角色末尾。
//
// on 的含义(程序用来分桶挑台词):
//   intro     首次登场
//   idle      一段时间无操作/空闲冒泡
//   shake     摇树过程中(含连摇)
//   tap       玩家点击该角色
//   event     随机事件(小鸟/牛顿/流星)出现或领取时
//   milestone 送达进度里程碑(10/25/50/75/90/99/100%)
//   era       进入新时代
//   buy       购买/升档时
//   egg       发现彩蛋时
//   away      离线回来
//   finale    82 亿到达 / 结局

export type CharId =
  | 'laoxu'
  | 'santa'
  | 'newton'
  | 'xiaoman'
  | 'crow'
  | 'laohai'
  | 'dudu'
  | 'doorman'
  | 'tree'
  | 'duoduo';

export type CharOn =
  | 'intro'
  | 'idle'
  | 'shake'
  | 'tap'
  | 'event'
  | 'milestone'
  | 'era'
  | 'buy'
  | 'egg'
  | 'away'
  | 'finale';

export interface CharLine {
  id: string;
  on: CharOn;
  text: string;
  /** 触发场景(人话描述) */
  trigger: string;
}

export interface Character {
  id: CharId;
  name: string;
  /** 一句话人设 */
  role: string;
  /** 口吻要点(写新台词时对照) */
  voice: string;
  /** 首次登场时代(0..5) */
  firstEra: 0 | 1 | 2 | 3 | 4 | 5;
  /** 招牌句 */
  catchphrase: string;
  lines: CharLine[];
}

type Row = [on: CharOn, text: string, trigger: string];
const mk = (k: string, rows: Row[]): CharLine[] =>
  rows.map(([on, text, trigger], i) => ({ id: `c-${k}-${String(i + 1).padStart(2, '0')}`, on, text, trigger }));

