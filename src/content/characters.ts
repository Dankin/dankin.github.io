export const CHAR_BY_ID: Record<CharId, Character> = Object.fromEntries(CHARACTERS.map((c) => [c.id, c])) as Record<CharId, Character>;

/** 按触发类型取台词池 */
export function linesFor(id: CharId, on: CharOn): CharLine[] {
  return CHAR_BY_ID[id].lines.filter((l) => l.on === on);
}
