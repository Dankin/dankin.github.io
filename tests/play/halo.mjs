import { Play, sleep, go, now, snapSave, texts, launchFromSave } from './lib.mjs';
const p = await launchFromSave('halo', process.argv[2] || 'after-noon');
const s = p.s;
let st = await s.state();
p.log('起点', JSON.stringify({ now: st.now, phase: st.phase, xl: st.stories.xiaolan_story, check: st.checklist }));
const t0 = st.now;
await go(p, 'snowman_r', 'snowman_pose_r'); p.log('pose @', ((await now(p)) - t0).toFixed(1));
st = await s.state(); p.log('pose后 xl', JSON.stringify(st.stories.xiaolan_story.done));
await go(p, 'mirror', 'mirror_tilt'); p.log('镜 @', ((await now(p)) - t0).toFixed(1));
await sleep(5000);
st = await s.state();
p.log('结果', JSON.stringify({ check: st.checklist, xl: st.stories.xiaolan_story.done, fin: st.stories.xiaolan_story.finished }));
const r = await p.dump();
p.log('台词', JSON.stringify(texts(r, 0).map(t => `${t.now}:${t.tx}`).filter(x => /天使|光环|缺点|化|抽象/.test(x))));
await p.shot('halo');
p.log('errors', JSON.stringify(s.errors), 'dataWarn', s.dataWarnings.length);
await p.close();
