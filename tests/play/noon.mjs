import { Play, sleep, go, now, snapSave, texts, launchFromSave } from './lib.mjs';
const p = await launchFromSave('noon', 'after-morning2');
const s = p.s;
const waitStep = (story, step, ms) => s.waitStep(story, step, { timeout: ms }).then(() => true).catch(e => { p.log(`${story}/${step} 未完成: ${e.message.split('\n')[0]}`); return false; });
let st = await s.state();
p.log('继续:', JSON.stringify({ now: st.now, phase: st.phase, laozhou: st.stories.laozhou_story.current, xiaolan: st.stories.xiaolan_story.current }));
const M = {};
// ===== 老周线 =====
M.lz0 = await now(p); p.log('--- 老周线开始');
await go(p, 'lamp_bk1', 'lamp_apron');
await waitStep('laozhou_story', 'see', 15000);
p.log('see 完成', (await now(p)).toFixed(1));
await p.shot('lz-see');
await go(p, 'vending', 'vend_cookie');
await waitStep('laozhou_story', 'cookie', 15000);
p.log('cookie 完成', (await now(p)).toFixed(1));
await waitStep('laozhou_story', 'crowd', 60000);
p.log('crowd 完成', (await now(p)).toFixed(1));
await p.shot('lz-crowd');
await go(p, 'oven', 'oven_stoke');
await waitStep('laozhou_story', 'ember', 15000);
p.log('ember 完成', (await now(p)).toFixed(1));
await waitStep('laozhou_story', 'bake', 90000);
await p.waitDone('laozhou_story', 120000).catch(e => p.log('laozhou finish 未完成'));
await s.waitIdle({ timeout: 120000 }).catch(() => {});
M.lz1 = await now(p);
p.log('老周线 完成, game 用时=', (M.lz1 - M.lz0).toFixed(1));
await p.shot('lz-done');
await snapSave(p, 'after-laozhou');
// ===== 小蓝线 =====
st = await s.state();
p.log('小蓝 当前', st.stories.xiaolan_story.current, 'npc visible', st.npcs.xiaolan.visible);
M.xl0 = await now(p); p.log('--- 小蓝线开始');
await go(p, 'bike_xl', 'bike_bell');
await waitStep('xiaolan_story', 'bell', 20000);
p.log('bell 完成', (await now(p)).toFixed(1));
await p.shot('xl-bell');
await go(p, 'bread_cart', 'bread_scent_re');
await waitStep('xiaolan_story', 'smell', 20000);
p.log('smell 完成', (await now(p)).toFixed(1));
await go(p, 'bike_xl', 'bike_roll');
await waitStep('xiaolan_story', 'bike', 20000);
p.log('bike 完成', (await now(p)).toFixed(1));
await s.waitIdle({ timeout: 60000 }).catch(() => {});
await go(p, 'snowman_r', 'snowman_pose_r');
await waitStep('xiaolan_story', 'pose', 20000);
p.log('pose 完成', (await now(p)).toFixed(1));
await p.shot('xl-pose');
await waitStep('xiaolan_story', 'paint', 90000);
await p.waitDone('xiaolan_story', 120000).catch(e => p.log('xiaolan finish 未完成'));
await s.waitIdle({ timeout: 120000 }).catch(() => {});
M.xl1 = await now(p);
p.log('小蓝线 完成, game 用时=', (M.xl1 - M.xl0).toFixed(1));
await p.shot('xl-done');
await sleep(3000);
st = await s.state();
p.log('after noon:', JSON.stringify({ phase: st.phase, warmth: st.warmth, stage: st.hat.stage, check: st.checklist }));
await snapSave(p, 'after-noon');
const r = await p.dump();
p.log('台词:', JSON.stringify(texts(r, M.lz0).map(t => `${t.now}:${t.tx}`)));
p.log('events:', JSON.stringify(r.events.filter(e => ['story','hint','check','phase'].includes(e.k)).map(e => `${e.now} ${e.k} ${e.v}`)));
p.log('errors:', JSON.stringify(s.errors), 'dataWarn', s.dataWarnings.length);
await p.close();
