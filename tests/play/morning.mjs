import { Play, sleep, go, now, snapSave, texts } from './lib.mjs';
const p = await Play.launch('main');
const s = p.s;
await s.start({ mode: 'new' });
const T0 = await now(p); p.log('开局 game.now=', T0);
const mark = {};
// ===== 小米线 =====
mark.xiaomi_start = await now(p);
p.log('--- 小米线开始');
await go(p, 'windchime', 'chime_ring');
await s.waitStep('xiaomi_story', 'listen', { timeout: 15000 }).catch(e => p.log('listen 未完成', e.message.split('\n')[0]));
p.log('listen:', (await s.state()).stories.xiaomi_story.done.join(','));
await go(p, 'balloon_stall', 'balloon_release');
await s.waitStep('xiaomi_story', 'calm', { timeout: 40000 }).catch(e => p.log('calm 未完成', e.message.split('\n')[0]));
await p.shot('xiaomi-calm');
p.log('calm:', (await s.state()).stories.xiaomi_story.done.join(','));
await go(p, 'speaker', 'speaker_prelude');
await s.waitStep('xiaomi_story', 'melody', { timeout: 20000 }).catch(e => p.log('melody 未完成', e.message.split('\n')[0]));
await p.shot('xiaomi-melody');
await p.waitDone('xiaomi_story', 90000).catch(e => p.log('xiaomi finish 未完成', e.message.split('\n')[0]));
await s.waitIdle({ timeout: 90000 }).catch(() => {});
mark.xiaomi_end = await now(p);
p.log('小米线 完成 用时(game s)=', (mark.xiaomi_end - mark.xiaomi_start).toFixed(1));
await p.shot('xiaomi-done');
await snapSave(p, 'after-xiaomi');
// ===== 阿福线 =====
mark.afu_start = await now(p);
p.log('--- 阿福线开始');
await go(p, 'fish_rack', 'fish_swing');
await s.waitStep('afu_story', 'wake', { timeout: 20000 }).catch(e => p.log('wake 未完成', e.message.split('\n')[0]));
await go(p, 'mailbox_alley', 'alley_post');
await s.waitStep('afu_story', 'drop', { timeout: 30000 }).catch(e => p.log('drop 未完成', e.message.split('\n')[0]));
await s.waitIdle({ timeout: 60000 }).catch(() => {});
await p.shot('afu-after-cat');
await go(p, 'radio', 'radio_lullaby');
await s.waitStep('afu_story', 'lull', { timeout: 30000 }).catch(e => p.log('lull 未完成', e.message.split('\n')[0]));
p.log('lull:', (await s.state()).stories.afu_story.done.join(','));
await p.waitStepDone('afu_story', 'enter', 90000).catch(e => p.log('enter 未完成', e.message.split('\n')[0]));
await p.waitDone('afu_story', 90000).catch(e => p.log('afu finish 未完成', e.message.split('\n')[0]));
await s.waitIdle({ timeout: 90000 }).catch(() => {});
mark.afu_end = await now(p);
p.log('阿福线 完成 用时(game s)=', (mark.afu_end - mark.afu_start).toFixed(1));
await p.shot('afu-done');
await sleep(3000);
const st = await s.state();
p.log('after morning:', JSON.stringify({ phase: st.phase, warmth: st.warmth, hat: st.hat.stage, check: st.checklist }));
await snapSave(p, 'after-morning');
const r = await p.dump('main-morning.rec.json');
p.log('台词:', JSON.stringify(texts(r).map(t => `${t.now}:${t.tx}`)));
p.log('events:', JSON.stringify(r.events.filter(e => ['story','hint','check','phase'].includes(e.k)).map(e => `${e.now} ${e.k} ${e.v}`)));
p.log('errors:', JSON.stringify(s.errors), 'dataWarn', s.dataWarnings.length);
await p.close();
