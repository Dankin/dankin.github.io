import { Play, sleep } from './lib.mjs';
const p = await Play.launch('smoke');
await p.shot('title');
await p.s.start({ mode: 'new' });
await p.s.waitState(s=>s.started);
let st = await p.st;
p.log('start', JSON.stringify({now:st.now,phase:st.phase,hat:st.hat,region:st.region,warmth:st.warmth}));
p.log('npcs', JSON.stringify(st.npcs));
await sleep(8000);
await p.shot('opening');
const r = await p.dump();
p.log('texts', JSON.stringify(r.texts)); p.log('events', JSON.stringify(r.events));
p.log('btns', JSON.stringify((await p.s.qa('uiButtons')).map(b=>[b.qa,b.label,Math.round(b.x),Math.round(b.y)])));
await p.close();
