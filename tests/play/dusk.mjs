import { Play, sleep, go, now, snapSave, texts, launchFromSave } from './lib.mjs';
const p = await launchFromSave('dusk', 'after-noon2');
const s = p.s;
const waitStep = (story, step, ms) => s.waitStep(story, step, { timeout: ms }).then(() => true).catch(e => { p.log(`${story}/${step} 未完成: ${e.message.split('\n')[0]}`); return false; });
let st = await s.state();
p.log('继续:', JSON.stringify({ now: st.now, phase: st.phase, adong: st.stories.adong_story.current, npcAdong: st.npcs.adong, hat: st.hat.stage }));
const M = {}; M.a0 = await now(p);
p.log('--- 阿冬线开始');
await p.shot('ad-00');
// 玩家第一反应：先点斜板（公交还没到）
await go(p, 'bus_door', 'bus_ramp');
await sleep(1500);
p.log('过早 bus_ramp 后 adong 步骤:', (await s.state()).stories.adong_story.done.join(','));
await p.shot('ad-early-ramp');
// 等公交到站
await s.waitState(q => q.npcs.adong.visible && q.npcs.adong.x > 30, { timeout: 90000 }).catch(() => p.log('adong 没到站?'));
st = await s.state(); p.log('adong 到位', JSON.stringify(st.npcs.adong), 'now', st.now.toFixed(1));
await go(p, 'bus_door', 'bus_ramp');
await waitStep('adong_story', 'ramp', 20000); p.log('ramp 完成', (await now(p)).toFixed(1));
await p.shot('ad-ramp');
await go(p, 'lamp_s1', 'lamp_glow_lamp_s1');
await waitStep('adong_story', 'light', 20000); p.log('light 完成', (await now(p)).toFixed(1));
await go(p, 'snowmachine', 'snow_blow');
await waitStep('adong_story', 'clear', 25000); p.log('clear 完成', (await now(p)).toFixed(1));
await p.shot('ad-clear');
await go(p, 'balloon_bundle', 'balloon_release_s');
await waitStep('adong_story', 'crowd', 30000); p.log('crowd 完成', (await now(p)).toFixed(1));
await waitStep('adong_story', 'start', 120000); p.log('start 完成', (await now(p)).toFixed(1));
await p.shot('ad-start');
await p.waitDone('adong_story', 150000).catch(() => p.log('adong finish 未完成'));
await s.waitIdle({ timeout: 150000 }).catch(() => {});
M.a1 = await now(p);
p.log('阿冬线 完成, game 用时=', (M.a1 - M.a0).toFixed(1));
await p.shot('ad-done');
await sleep(2000);
st = await s.state();
p.log('after dusk:', JSON.stringify({ phase: st.phase, warmth: st.warmth, stage: st.hat.stage, check: st.checklist, fin: st.stories.finale_story }));
await snapSave(p, 'after-dusk');
const r = await p.dump();
p.log('台词:', JSON.stringify(texts(r, M.a0).map(t => `${t.now}:${t.tx}`)));
p.log('events:', JSON.stringify(r.events.filter(e => ['story','hint','check','phase'].includes(e.k)).map(e => `${e.now} ${e.k} ${e.v}`)));
p.log('errors:', JSON.stringify(s.errors), 'dataWarn', s.dataWarnings.length);
await p.close();
