import { loadPlaywright, CHROME } from '../lib/pw.mjs';
const { chromium } = await loadPlaywright();
const b = await chromium.launch({ executablePath: CHROME, args: ['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
const ctx = await b.newContext({ viewport: { width: 1280, height: 720 } });
const p = await ctx.newPage();
const errs = []; p.on('console', m => { if (['error'].includes(m.type())) errs.push(m.text()); }); p.on('pageerror', e => errs.push('PE ' + e.message));
await p.goto('http://127.0.0.1:4173/?debug=1', { waitUntil: 'commit' });
await p.waitForTimeout(300);
await p.screenshot({ path: '/tmp/m3/shots/p-boot.png' });
console.log('boot el', await p.evaluate(() => !!document.getElementById('boot')));
await p.waitForTimeout(9000);
await p.screenshot({ path: '/tmp/m3/shots/p-title.png' });
console.log(await p.evaluate(() => ({ game: typeof window.__game, qa: typeof window.__qa, canvas: !!document.querySelector('canvas') })), errs);
await b.close();
